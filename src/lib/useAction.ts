import { useState, useCallback, useRef } from 'react';
import { ToastVariant } from '../components/ui/Toast';

export interface ActionReceipt<T = any> {
  title: string | ((result: T) => string);
  description?: string | ((result: T) => string);
  variant?: ToastVariant;
}

export interface ActionToastData {
  id: string;
  title: string;
  description?: string;
  variant: ToastVariant;
  onUndo?: () => void;
  undoLabel?: string;
}

export interface UseActionOptions<T = any> {
  /** Name of the action for idempotency namespace and logging */
  name: string;
  /** Primary execution function receiving the unique client-side idempotency key and arguments */
  onExecute: (context: { idempotencyKey: string; args: any[] }) => Promise<T> | T;
  /** Success handler called after execution finishes */
  onSuccess?: (result: T, context: { idempotencyKey: string }) => void;
  /** Error handler called on failure */
  onError?: (error: unknown, context: { idempotencyKey: string }) => void;
  /** Visual receipt configuration (toast feedback) */
  receipt?: ActionReceipt<T>;
  /** Reversibility & Undo support */
  undoable?: boolean;
  /** Undo action callback executed if user clicks Undo within duration (default 6000ms) */
  onUndo?: (context: { idempotencyKey: string; previousState?: any }) => Promise<void> | void;
  /** Label for undo button (default: "Undo") */
  undoLabel?: string;
  /** Duration in ms for undo toast to remain active (default: 6000ms per INTERACTION.md) */
  undoDurationMs?: number;
  /** Capture previous state before execution for rollback */
  capturePreviousState?: () => any;
  /** Minimum throttle duration in ms button remains disabled (default: 300ms) */
  minPendingMs?: number;
  /** Optional custom toast handler if parent page manages toast container */
  showToast?: (toast: ActionToastData) => void;
}

export interface UseActionResult<T = any> {
  /** Trigger the action */
  execute: (...args: any[]) => Promise<T | undefined>;
  /** Whether the action execution is in-flight */
  isPending: boolean;
  /** Whether the action is temporarily disabled (includes 300ms post-click throttle) */
  isDisabled: boolean;
  /** Whether execution is taking >400ms (Rule 10 spinner threshold) */
  isStillWorking: boolean;
  /** Cancel the pending execution (Rule 10) */
  cancel: () => void;
  /** The last generated idempotency key */
  idempotencyKey: string | null;
  /** Active toast generated by this action if not consumed by parent */
  actionToast: ActionToastData | null;
  /** Dismiss the action toast */
  dismissToast: () => void;
  /** Pre-wired button props to directly spread onto <Button> or <button> */
  buttonProps: {
    onClick: () => void;
    disabled: boolean;
    'aria-busy': boolean;
  };
}

/**
 * useAction hook enforcing:
 * 1. Client-side idempotency keys per invocation
 * 2. Minimum 300ms disabled-once-clicked state
 * 3. Receipt-of-action (concrete visible state change / toast)
 * 4. 6-second undo-toast for reversible operations
 */
export function useAction<T = any>(options: UseActionOptions<T>): UseActionResult<T> {
  const [isPending, setIsPending] = useState(false);
  const [isDisabled, setIsDisabled] = useState(false);
  const [isStillWorking, setIsStillWorking] = useState(false);
  const [idempotencyKey, setIdempotencyKey] = useState<string | null>(null);
  const [actionToast, setActionToast] = useState<ActionToastData | null>(null);

  const throttleTimerRef = useRef<NodeJS.Timeout | null>(null);
  const undoTimerRef = useRef<NodeJS.Timeout | null>(null);
  const stillWorkingTimerRef = useRef<NodeJS.Timeout | null>(null);

  const cancel = useCallback(() => {
    if (stillWorkingTimerRef.current) {
      clearTimeout(stillWorkingTimerRef.current);
      stillWorkingTimerRef.current = null;
    }
    setIsPending(false);
    setIsDisabled(false);
    setIsStillWorking(false);
  }, []);

  const dismissToast = useCallback(() => {
    if (undoTimerRef.current) {
      clearTimeout(undoTimerRef.current);
      undoTimerRef.current = null;
    }
    setActionToast(null);
  }, []);

  const execute = useCallback(
    async (...args: any[]): Promise<T | undefined> => {
      // Guard against double clicks / concurrent execution
      if (isPending || isDisabled) {
        return undefined;
      }

      // Generate client-side idempotency key
      const key = `act-${options.name}-${Date.now()}-${Math.random().toString(36).substring(2, 9)}`;
      setIdempotencyKey(key);
      setIsPending(true);
      setIsDisabled(true);
      setIsStillWorking(false);

      // Rule 10: 400ms threshold for spinner switching to "still working…" copy
      if (stillWorkingTimerRef.current) clearTimeout(stillWorkingTimerRef.current);
      stillWorkingTimerRef.current = setTimeout(() => {
        setIsStillWorking(true);
      }, 400);

      const previousState = options.capturePreviousState ? options.capturePreviousState() : undefined;

      try {
        const result = await options.onExecute({ idempotencyKey: key, args });

        // Handle undoable toast or receipt
        if (options.undoable && options.onUndo) {
          const duration = options.undoDurationMs || 6000;
          const toastData: ActionToastData = {
            id: `toast-undo-${Date.now()}`,
            variant: options.receipt?.variant || 'info',
            title:
              typeof options.receipt?.title === 'function'
                ? options.receipt.title(result)
                : options.receipt?.title || 'Action completed',
            description:
              typeof options.receipt?.description === 'function'
                ? options.receipt.description(result)
                : options.receipt?.description || 'Click Undo to revert this change.',
            undoLabel: options.undoLabel || 'Undo',
            onUndo: async () => {
              try {
                await options.onUndo!({ idempotencyKey: key, previousState });
                dismissToast();
              } catch (undoErr) {
                console.error('Failed to undo action:', undoErr);
              }
            },
          };

          if (options.showToast) {
            options.showToast(toastData);
          } else {
            setActionToast(toastData);
          }

          if (undoTimerRef.current) clearTimeout(undoTimerRef.current);
          undoTimerRef.current = setTimeout(() => {
            dismissToast();
          }, duration);
        } else if (options.receipt) {
          const toastData: ActionToastData = {
            id: `toast-${Date.now()}`,
            variant: options.receipt.variant || 'success',
            title:
              typeof options.receipt.title === 'function'
                ? options.receipt.title(result)
                : options.receipt.title,
            description:
              typeof options.receipt.description === 'function'
                ? options.receipt.description(result)
                : options.receipt.description,
          };

          if (options.showToast) {
            options.showToast(toastData);
          } else {
            setActionToast(toastData);
          }
        }

        options.onSuccess?.(result, { idempotencyKey: key });
        return result;
      } catch (err) {
        options.onError?.(err, { idempotencyKey: key });
        throw err;
      } finally {
        if (stillWorkingTimerRef.current) {
          clearTimeout(stillWorkingTimerRef.current);
          stillWorkingTimerRef.current = null;
        }
        setIsPending(false);
        setIsStillWorking(false);
        // Enforce 300ms minimum post-click disabled state for idempotency safety
        const throttleDuration = options.minPendingMs || 300;
        if (throttleTimerRef.current) clearTimeout(throttleTimerRef.current);
        throttleTimerRef.current = setTimeout(() => {
          setIsDisabled(false);
        }, throttleDuration);
      }
    },
    [options, isPending, isDisabled, dismissToast]
  );

  return {
    execute,
    isPending,
    isDisabled,
    isStillWorking,
    cancel,
    idempotencyKey,
    actionToast,
    dismissToast,
    buttonProps: {
      onClick: () => {
        execute();
      },
      disabled: isDisabled || isPending,
      'aria-busy': isPending,
    },
  };
}
